"""Write docs/code/api_reference.md from the code: modules, classes, functions, who imports whom.

The file is generated, so it cannot drift from the code. Do not edit it by hand.

    uv run python scripts/make_api_reference.py            # (re)write the file
    uv run python scripts/make_api_reference.py --check    # exit 1 if the file is out of date

What it reads (with the ast module, without importing or running any of the code):
  * the module docstring of every file in src/pdac_cfrna and scripts,
  * every top-level class (with its fields and methods) and function: signature + docstring,
  * the imports of `pdac_cfrna` modules, to list which files use which.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PACKAGE = "pdac_cfrna"
SRC_DIR = REPO_ROOT / "src" / PACKAGE
SCRIPTS_DIR = REPO_ROOT / "scripts"
OUT_PATH = REPO_ROOT / "docs" / "code" / "api_reference.md"
SELF = Path(__file__).name

HEADER = """# API reference (generated)

> Generated by `scripts/make_api_reference.py` from the code. **Do not edit by hand**: change the
> docstrings in the code and run `uv run python scripts/make_api_reference.py`.
> `--check` fails when this file is out of date.

Read next: [task_map.md](task_map.md) (what to run for what) and
[execution_flows.md](execution_flows.md) (what happens when you run it).
"""


def first_paragraph(doc: str | None) -> str:
    """The first paragraph of a docstring on one line ('' if there is no docstring)."""
    if not doc:
        return ""
    return " ".join(doc.strip().split("\n\n")[0].split())


def signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    """`name(args) -> returns` as written in the source."""
    args = ast.unparse(node.args)
    returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    return f"{node.name}({args}){returns}"


def imported_modules(tree: ast.Module) -> set[str]:
    """Names of pdac_cfrna modules imported by this file (`from pdac_cfrna.x import y` -> x)."""
    found: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            parts = node.module.split(".")
            if parts[0] == PACKAGE and len(parts) > 1:
                found.add(parts[1])
            elif node.module == PACKAGE:
                found.update(alias.name for alias in node.names)
        elif isinstance(node, ast.Import):
            for alias in node.names:
                parts = alias.name.split(".")
                if parts[0] == PACKAGE and len(parts) > 1:
                    found.add(parts[1])
    return found


def class_fields(node: ast.ClassDef) -> list[str]:
    """Annotated fields of a class body (dataclass / pydantic style): `name: type = default`."""
    fields = []
    for item in node.body:
        if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
            default = f" = {ast.unparse(item.value)}" if item.value is not None else ""
            fields.append(f"{item.target.id}: {ast.unparse(item.annotation)}{default}")
    return fields


def render_function(node: ast.FunctionDef | ast.AsyncFunctionDef, indent: str = "") -> list[str]:
    summary = first_paragraph(ast.get_docstring(node)) or "_no docstring_"
    is_property = any(ast.unparse(d) == "property" for d in node.decorator_list)
    tag = "property " if is_property else ""
    return [f"{indent}- {tag}`{signature(node)}`", f"{indent}  {summary}"]


def render_module(path: Path, kind: str, used_by: dict[str, list[str]]) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    name = path.stem
    rel = path.relative_to(REPO_ROOT).as_posix()
    lines = [f"## `{rel}`", ""]
    doc = ast.get_docstring(tree)
    if doc:
        lines += [doc.strip().split("\n\n")[0].strip(), ""]

    own = name if kind == "src" else ""  # a script may import the module of the same name
    uses = sorted(m for m in imported_modules(tree) if m != own)
    if uses:
        lines.append(f"- Uses: {', '.join(f'`{m}`' for m in uses)}")
    if kind == "src" and used_by.get(name):
        lines.append(f"- Used by: {', '.join(f'`{m}`' for m in used_by[name])}")
    if lines[-1] != "":
        lines.append("")

    classes = [n for n in tree.body if isinstance(n, ast.ClassDef)]
    functions = [n for n in tree.body if isinstance(n, ast.FunctionDef | ast.AsyncFunctionDef)]
    public = [f for f in functions if not f.name.startswith("_")]
    private = [f for f in functions if f.name.startswith("_")]

    if classes:
        lines += ["**Classes**", ""]
        for cls in classes:
            summary = first_paragraph(ast.get_docstring(cls))
            lines.append(f"- `class {cls.name}`" + (f": {summary}" if summary else ""))
            for field in class_fields(cls):
                lines.append(f"  - field `{field}`")
            for method in cls.body:
                if isinstance(method, ast.FunctionDef) and (
                    not method.name.startswith("_") or method.name == "__init__"
                ):
                    lines += render_function(method, "  ")
        lines.append("")
    if public:
        lines += ["**Functions**", ""]
        for fn in public:
            lines += render_function(fn)
        lines.append("")
    if private:
        lines += ["**Private helpers**", ""]
        for fn in private:
            lines += render_function(fn)
        lines.append("")
    return lines


def build() -> str:
    src_files = sorted(p for p in SRC_DIR.glob("*.py") if p.name != "__init__.py")
    script_files = sorted(p for p in SCRIPTS_DIR.glob("*.py") if p.name != SELF)

    used_by: dict[str, list[str]] = {}
    for path, label in [(p, p.stem) for p in src_files] + [
        (p, f"scripts/{p.name}") for p in script_files
    ]:
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for module in imported_modules(tree):
            used_by.setdefault(module, []).append(label)
    used_by = {k: sorted(set(v)) for k, v in used_by.items()}

    lines = [HEADER, "## Contents", ""]
    lines += [f"- [`src/{PACKAGE}/{p.name}`](#srcpdac_cfrna{p.stem}py)" for p in src_files]
    lines += [f"- [`scripts/{p.name}`](#scripts{p.stem}py)" for p in script_files]
    lines.append("")
    lines += ["# Package modules (`src/pdac_cfrna`)", ""]
    for path in src_files:
        lines += render_module(path, "src", used_by)
    lines += ["# Scripts (`scripts/`)", ""]
    for path in script_files:
        lines += render_module(path, "script", used_by)
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT_PATH.read_text(encoding="utf-8") if OUT_PATH.is_file() else ""
        if current != text:
            print(
                f"{OUT_PATH.relative_to(REPO_ROOT)} is out of date: "
                "run `uv run python scripts/make_api_reference.py`"
            )
            return 1
        print("api_reference.md is up to date")
        return 0
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT_PATH.relative_to(REPO_ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
